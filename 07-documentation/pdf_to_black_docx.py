def setup(doc):
    section = doc.sections[0]
    section.top_margin = Cm(2)
    section.bottom_margin = Cm(2)
    section.left_margin = Cm(2.5)
    section.right_margin = Cm(2.5)

    s = doc.styles["Normal"]
    s.font.name = "Times New Roman"
    s.font.size = Pt(12)
    s.font.color.rgb = BLACK
    s._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    s.paragraph_format.line_spacing = 1.15
    s.paragraph_format.space_after = Pt(6)

    for level in (1, 2):
        h = doc.styles[f"Heading {level}"]
        h.font.name = "Times New Roman"
        h.font.bold = True
        h.font.size = Pt(14 if level == 1 else 12)
        h.font.color.rgb = BLACK
        h._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")


def page_number(section):
    footer = section.footer
    p = footer.paragraphs[0] if footer.paragraphs else footer.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run()
    for tag, val in [("begin", None), (None, " PAGE "), ("end", None)]:
        if tag:
            el = OxmlElement("w:fldChar")
            el.set(qn("w:fldCharType"), tag)
            run._r.append(el)
        else:
            el = OxmlElement("w:instrText")
            el.set(qn("xml:space"), "preserve")
            el.text = val
            run._r.append(el)
    run.font.size = Pt(10)
    run.font.color.rgb = BLACK
    run.font.name = "Times New Roman"


def add_run(p, text, bold=False, size=12):
    r = p.add_run(text)
    r.font.name = "Times New Roman"
    r._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    r.font.size = Pt(size)
    r.font.color.rgb = BLACK
    r.bold = bold
    return r


def center(doc, text, bold=False, size=12, space_after=6):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_after = Pt(space_after)
    add_run(p, text, bold=bold, size=size)
    return p


def para(doc, text, bold=False, first_line=True, space_after=6):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(space_after)
    if first_line:
        p.paragraph_format.first_line_indent = Cm(1.25)
    add_run(p, text, bold=bold)
    return p


def heading(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(12)
    p.paragraph_format.space_after = Pt(8)
    p.paragraph_format.first_line_indent = Cm(0)
    add_run(p, text, bold=True, size=12)
    return p


def bullet(doc, text):
    p = doc.add_paragraph(style="List Bullet")
    p.clear()
    p.paragraph_format.space_after = Pt(4)
    p.paragraph_format.left_indent = Cm(1.0)
    add_run(p, text)
    return p


def set_cell_black(cell):
    for p in cell.paragraphs:
        for r in p.runs:
            r.font.color.rgb = BLACK
            r.font.name = "Times New Roman"
            r.font.size = Pt(11)


