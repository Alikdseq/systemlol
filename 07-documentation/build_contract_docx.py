def setup(doc):
    s = doc.styles["Normal"]
    s.font.name = "Times New Roman"
    s.font.size = Pt(12)
    s.font.color.rgb = DARK
    s.paragraph_format.line_spacing = 1.15
    s.paragraph_format.space_after = Pt(6)
    for i, sz in [(1, 14), (2, 13)]:
        h = doc.styles[f"Heading {i}"]
        h.font.name = "Times New Roman"
        h.font.bold = True
        h.font.size = Pt(sz)
        h.font.color.rgb = WINE


def page_number(section):
    footer = section.footer
    p = footer.paragraphs[0] if footer.paragraphs else footer.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run()
    for tag, val in [("begin", None), (None, " PAGE "), ("end", None)]:
        if tag:
            el = OxmlElement("w:fldChar")
            el.set(qn("w:fldCharType"), tag)
            run._r.append(el)
        else:
            el = OxmlElement("w:instrText")
            el.set(qn("xml:space"), "preserve")
            el.text = val
            run._r.append(el)
    run.font.size = Pt(10)


def center(doc, text, size=12, bold=False):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    r.font.size = Pt(size)
    r.bold = bold
    r.font.name = "Times New Roman"


def para(doc, text, indent=False, bold=False):
    p = doc.add_paragraph()
    if indent:
        p.paragraph_format.first_line_indent = Cm(1.25)
    r = p.add_run(text)
    r.font.name = "Times New Roman"
    r.font.size = Pt(12)
    r.bold = bold
    return p


def clause(doc, num, title, body_parts):
    p = doc.add_paragraph()
    r = p.add_run(f"{num}. {title}")
    r.bold = True
    r.font.name = "Times New Roman"
    r.font.size = Pt(12)
    for part in body_parts:
        if isinstance(part, list):
            for item in part:
                doc.add_paragraph(item, style="List Bullet")
        else:
            para(doc, part, indent=True)


